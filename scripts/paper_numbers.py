if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--release", default="v1.0")
    a = ap.parse_args()
    rel = config.RELEASE / a.release
    rel = rel if rel.exists() else None
    n = numbers(rel)
    tables(rel)
    print(sum(v == TBD for v in n.values()), "numbers still TBD")
